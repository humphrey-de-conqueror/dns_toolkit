
from pathlib import Path

from dns_toolkit.bind_config import render_zone_file
from dns_toolkit.deployment.config_editor import read_candidate_config
from dns_toolkit.deployment.plan import DeploymentPlan
from dns_toolkit.models import Zone
from dns_toolkit.validators.zone_validator import validate_zone


DEFAULT_CONFIG_PATH = Path("/etc/bind/named.conf")
DEFAULT_ZONE_DIRECTORY = Path("/etc/bind/zones")
MANAGED_INCLUDE_PATH = Path("/etc/bind/dns-toolkit-zones.conf")


class DeploymentPlanBuilder:
        def build(
                self,
                zones: list[Zone],
                config_path: Path = DEFAULT_CONFIG_PATH,
                zone_directory: Path = DEFAULT_ZONE_DIRECTORY,
                target_name: str = "Local BIND 9",
                serial: int = 1,
        ) -> DeploymentPlan:
                files: dict[Path, str] = {}
                errors: list[str] = []
                declarations: list[str] = []

                if config_path != DEFAULT_CONFIG_PATH:
                        errors.append(
                                "Local deployment currently supports only "
                                f"{DEFAULT_CONFIG_PATH}."
                        )

                if zone_directory != DEFAULT_ZONE_DIRECTORY:
                        errors.append(
                                "Local deployment currently supports only "
                                f"{DEFAULT_ZONE_DIRECTORY}."
                        )

                if not zones:
                        errors.append("There are no zones to deploy.")

                seen_names: set[str] = set()

                for zone in zones:
                        zone_errors = validate_zone(zone)

                        if zone_errors:
                                errors.extend(
                                        f"{zone.name}: {error}"
                                        for error in zone_errors
                                )
                                continue

                        normalized_name = (
                                zone.name.rstrip(".").lower()
                        )

                        if normalized_name in seen_names:
                                errors.append(
                                        f"Duplicate zone: {normalized_name}"
                                )
                                continue

                        seen_names.add(normalized_name)

                        zone_path = (
                                DEFAULT_ZONE_DIRECTORY
                                / f"db.{normalized_name}"
                        )

                        try:
                                zone_content = render_zone_file(
                                        zone,
                                        serial=serial,
                                )
                        except ValueError as error:
                                errors.append(
                                        f"{zone.name}: {error}"
                                )
                                continue

                        files[zone_path] = zone_content
                        declarations.append(
                                self._render_declaration(
                                        normalized_name,
                                        zone_path,
                                )
                        )

                files[MANAGED_INCLUDE_PATH] = (
                        "# Generated by DNS Toolkit. Do not edit manually.\n\n"
                        + "\n".join(declarations)
                        + ("\n" if declarations else "")
                )

                try:
                        candidate_config = read_candidate_config(
                                config_path
                        )
                        files[config_path] = candidate_config
                except (OSError, ValueError) as error:
                        errors.append(
                                f"Could not prepare candidate configuration: "
                                f"{error}"
                        )

                return DeploymentPlan(
                        target_name=target_name,
                        config_path=config_path,
                        files=files,
                        validation_errors=errors,
                )

        @staticmethod
        def _render_declaration(
                zone_name: str,
                zone_path: Path,
        ) -> str:
                escaped_path = str(zone_path).replace(
                        "\\",
                        "\\\\",
                ).replace('"', '\\"')

                return (
                        f'zone "{zone_name}" {{\n'
                        "        type master;\n"
                        f'        file "{escaped_path}";\n'
                        "};\n"
                )
